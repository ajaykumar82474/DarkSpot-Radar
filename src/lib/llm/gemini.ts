/**
 * Google Gemini LLM Adapter.
 * Uses Google Gen AI SDK (with graceful REST fallback) reading GEMINI_API_KEY server-side only.
 * Enforces structured JSON output conforming to Zod schema.
 */

import { GoogleGenAI } from "@google/genai";
import { LLMExtractionOutputSchema } from "@/types/schemas";
import { LLMAnalysisRawResult } from "./types";

export class GeminiAdapter {
  private apiKey: string;

  constructor(apiKey?: string) {
    this.apiKey = apiKey || process.env.GEMINI_API_KEY || "";
  }

  async analyze(
    topic: string,
    sources: { id: string; title: string; rawText: string }[]
  ): Promise<LLMAnalysisRawResult> {
    if (!this.apiKey) {
      throw new Error("GEMINI_API_KEY is not configured.");
    }

    const sourcesPayload = sources
      .map(
        (s) =>
          `SOURCE_ID: ${s.id}\nSOURCE_TITLE: ${s.title}\nCONTENT:\n${s.rawText.slice(0, 8000)}\n---`
      )
      .join("\n\n");

    const systemPrompt = `You are DarkSpot Radar, an expert gap-detection and contradiction-auditing engine for high-stakes decision making.
Your mandate is NOT to summarize, but to reveal WHAT IS MISSING, WHAT CONFLICTS, and WHAT IS UNCERTAIN across the reviewed sources.

RULES:
1. EXPECTATION-FIRST: First generate 6 to 8 critical dimensions that a prudent, careful person MUST know for this specific topic type ("${topic}").
2. QUOTE-VERIFIED EVIDENCE: For every claim you extract from a source, provide an EXACT, VERBATIM quote of 8-30 words directly copied from that source's text. Do NOT paraphrase or invent quotes.
3. THREE-LABEL HONESTY: AI findings must be labelled as potential signals/gaps ("GAP", "CONFLICT", "STALE", "UNANSWERED").
4. CONFLICT DETECTION: Identify competing statements (amounts, eligibility criteria, dates, documents required) across sources.
5. Provide your output strictly as a JSON object adhering to the schema below without markdown backticks or extra text.

JSON Schema format:
{
  "dimensions": [
    { "id": "dim-1", "name": "...", "description": "...", "importance": "CRITICAL" | "HIGH" | "MEDIUM" }
  ],
  "claims": [
    { "dimensionId": "dim-1", "sourceId": "...", "statement": "...", "quote": "..." }
  ],
  "findings": [
    { "type": "GAP" | "CONFLICT" | "STALE" | "UNANSWERED", "dimensionId": "dim-1", "title": "...", "description": "...", "severity": "CRITICAL" | "HIGH" | "MEDIUM" | "LOW", "confidence": 0.9, "sourceIds": ["..."], "quote": "...", "recommendedAction": "..." }
  ],
  "conflicts": [
    {
      "dimensionId": "dim-1",
      "aspect": "...",
      "comparisons": [
        { "sourceId": "...", "statedValue": "...", "quote": "..." }
      ],
      "resolutionReasoning": "..."
    }
  ],
  "executiveOverview": "..."
}`;

    const userPrompt = `TOPIC: ${topic}\n\nSOURCES TO AUDIT:\n${sourcesPayload}\n\nPerform full gap and contradiction analysis. Return valid JSON only.`;

    try {
      const ai = new GoogleGenAI({ apiKey: this.apiKey });
      const response = await ai.models.generateContent({
        model: "gemini-2.5-flash",
        contents: [
          { role: "user", parts: [{ text: `${systemPrompt}\n\n${userPrompt}` }] },
        ],
        config: {
          responseMimeType: "application/json",
          temperature: 0.1, // low temperature for precise factual quote extraction
        },
      });

      const responseText = response.text || "";
      const cleaned = responseText.replace(/^```json\s*/, "").replace(/\s*```$/, "").trim();
      const parsed = JSON.parse(cleaned);

      return LLMExtractionOutputSchema.parse(parsed);
    } catch (sdkError) {
      // Fallback via standard REST API if SDK call fails
      return await this.callRestFallback(systemPrompt, userPrompt);
    }
  }

  private async callRestFallback(systemPrompt: string, userPrompt: string): Promise<LLMAnalysisRawResult> {
    const url = `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=${this.apiKey}`;

    const res = await fetch(url, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        contents: [
          {
            role: "user",
            parts: [{ text: `${systemPrompt}\n\n${userPrompt}` }],
          },
        ],
        generationConfig: {
          responseMimeType: "application/json",
          temperature: 0.1,
        },
      }),
    });

    if (!res.ok) {
      const errText = await res.text();
      throw new Error(`Gemini API error: HTTP ${res.status} - ${errText}`);
    }

    const json = await res.json();
    const candidateText = json.candidates?.[0]?.content?.parts?.[0]?.text;
    if (!candidateText) {
      throw new Error("No response generated by Gemini model.");
    }

    const cleaned = candidateText.replace(/^```json\s*/, "").replace(/\s*```$/, "").trim();
    const parsed = JSON.parse(cleaned);

    return LLMExtractionOutputSchema.parse(parsed);
  }
}
